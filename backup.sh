#!/bin/sh
# remarkable2-backup - automatic backups of a reMarkable tablet over SSH.
# Waits for the tablet to appear on the network, then copies its document
# store into a dated .tar archive. Nothing is installed on the tablet.

RM_HOST="${RM_HOST:-}"
RM_USER="${RM_USER:-root}"
SSH_PORT="${SSH_PORT:-22}"
KEEP="${KEEP:-8}"
INTERVAL_HOURS="${INTERVAL_HOURS:-24}"
TEST_RUN="${TEST_RUN:-0}"

SSH_DIR=/ssh
ARCHIVE_DIR=/archives
KEY="$SSH_DIR/id_ed25519"
KNOWN_HOSTS="$SSH_DIR/known_hosts"
REMOTE_DIR=/home/root/.local/share/remarkable
ERR_FILE=/tmp/ssh.err

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') $*"; }

if [ -z "$RM_HOST" ]; then
  log "ERROR: RM_HOST is not set. Set it to your tablet's IP address."
  exit 1
fi

mkdir -p "$SSH_DIR" "$ARCHIVE_DIR"

if [ -f "$KEY" ]; then
  log "Existing SSH key found - reusing it"
else
  log "No SSH key found - generating a new one"
  ssh-keygen -q -t ed25519 -N "" -f "$KEY" -C remarkable2-backup
fi
echo "=== Public key to add to the tablet's ~/.ssh/authorized_keys ==="
cat "$KEY.pub"
echo "================================================================"

FORCE=0
RETRIED=0
if [ "$TEST_RUN" = "1" ]; then
  log "TEST_RUN: planting a fake tablet host key and forcing a backup"
  rm -f /tmp/fake /tmp/fake.pub
  ssh-keygen -q -t ed25519 -N "" -f /tmp/fake
  if [ "$SSH_PORT" = "22" ]; then hostspec="$RM_HOST"; else hostspec="[$RM_HOST]:$SSH_PORT"; fi
  echo "$hostspec $(cut -d' ' -f1,2 /tmp/fake.pub)" > "$KNOWN_HOSTS"
  FORCE=1
fi

do_backup() {
  ssh -i "$KEY" -p "$SSH_PORT" \
      -o BatchMode=yes -o ConnectTimeout=10 \
      -o ServerAliveInterval=15 -o ServerAliveCountMax=4 \
      -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile="$KNOWN_HOSTS" \
      "$RM_USER@$RM_HOST" "tar cf - -C $REMOTE_DIR xochitl" \
      > "$ARCHIVE_DIR/.partial.tar" 2> "$ERR_FILE" \
  && tar tf "$ARCHIVE_DIR/.partial.tar" > /dev/null 2>&1
}

backup_due() {
  [ "$FORCE" = "1" ] && return 0
  # shellcheck disable=SC2012 # archive names are generated by this script
  last=$(ls -1t "$ARCHIVE_DIR"/remarkable-*.tar 2> /dev/null | head -n 1)
  [ -z "$last" ] && return 0
  age=$(( $(date +%s) - $(stat -c %Y "$last") ))
  [ "$age" -ge $(( INTERVAL_HOURS * 3600 )) ]
}

log "Watching for tablet at $RM_HOST (backup every ${INTERVAL_HOURS}h, keeping $KEEP)"
while true; do
  if ! backup_due; then
    sleep 600; continue
  fi
  if ! ping -c 1 -W 2 "$RM_HOST" > /dev/null 2>&1; then
    sleep 60; continue
  fi

  stamp=$(date +%Y-%m-%d_%H%M)
  log "Tablet online - backup starting..."
  if do_backup; then
    mv "$ARCHIVE_DIR/.partial.tar" "$ARCHIVE_DIR/remarkable-$stamp.tar"
    log "Backup OK: remarkable-$stamp.tar ($(du -h "$ARCHIVE_DIR/remarkable-$stamp.tar" | cut -f1))"
    # shellcheck disable=SC2012
    ls -1t "$ARCHIVE_DIR"/remarkable-*.tar | tail -n +$(( KEEP + 1 )) | xargs -r rm -f
    FORCE=0; RETRIED=0
  elif [ "$RETRIED" != "1" ] && grep -q "IDENTIFICATION HAS CHANGED" "$ERR_FILE"; then
    rm -f "$ARCHIVE_DIR/.partial.tar"
    ssh-keygen -R "$RM_HOST" -f "$KNOWN_HOSTS" > /dev/null 2>&1
    ssh-keygen -R "[$RM_HOST]:$SSH_PORT" -f "$KNOWN_HOSTS" > /dev/null 2>&1
    log "Tablet SSH host key changed (normal after a firmware update) - accepted new key, retrying"
    RETRIED=1
  else
    rm -f "$ARCHIVE_DIR/.partial.tar"
    log "SSH said: $(grep -v '^@' "$ERR_FILE" | grep -v '^$' | head -n 3 | tr '\n' ' ')"
    log "Backup FAILED although tablet was online - retrying in 10 min"
    RETRIED=0
    sleep 600
  fi
done
